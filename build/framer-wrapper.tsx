/* the stops' copy windows, in scroll progress — the same numbers the template
   uses in its data-in / data-out attributes */
const COPY_WINDOWS: [number, number][] = [
    [0.005, 0.355],
    [0.415, 0.565],
    [0.585, 0.712],
    [0.72, 0.85],
    [0.86, 0.98],
]

const smooth = (a: number, b: number, v: number) => {
    const t = Math.max(0, Math.min(1, (v - a) / (b - a || 1)))
    return t * t * (3 - 2 * t)
}

/**
 * @framerSupportedLayoutWidth any-prefer-fixed
 * @framerSupportedLayoutHeight any-prefer-fixed
 * @framerIntrinsicWidth 1440
 * @framerIntrinsicHeight 900
 */
export default function ShadestateWalkthrough(props: Props) {
    const trackRef = useRef<HTMLDivElement>(null)
    const hostRef = useRef<HTMLDivElement>(null)
    const instRef = useRef<any>(null)
    const copyRefs = useRef<(HTMLDivElement | null)[]>([])
    const [status, setStatus] = useState<"loading" | "ready" | "failed">("loading")

    /* the copy fades in and out with progress; refs only, so the scene's frame
       loop never re-renders React */
    const paint = (p: number) => {
        copyRefs.current.forEach((el, i) => {
            if (!el) return
            const [a, b] = COPY_WINDOWS[i]
            const f = Math.min(0.018, (b - a) * 0.25)
            const o = Math.min(smooth(a, a + f, p), 1 - smooth(b - f, b, p))
            el.style.opacity = o.toFixed(3)
            el.style.transform = i === 1 ? "translate(-50%,-50%)" : `translate3d(0,${((1 - o) * 14).toFixed(2)}px,0)`
        })
    }

    /* mount once per quality tier / height: those rebuild the renderer */
    useEffect(() => {
        let cancelled = false
        const host = hostRef.current
        if (!host) return
        setStatus("loading")
        createWalkthrough(host, {
            scrollDriven: props.scrollDriven,
            autoplay: props.autoplay,
            loop: props.loop,
            speed: props.speed,
            startStop: props.startStop,
            timeOfDay: props.timeOfDay,
            cloudCover: props.cloudCover,
            grassDensity: props.grassDensity,
            waterRipples: props.waterRipples,
            palms: props.palms,
            city: props.city,
            pausedOffscreen: props.pausedOffscreen,
            three: THREE_NPM,
            quality: props.quality,
            dprMax: props.maxDpr,
            height: props.sectionHeight > 0 ? props.sectionHeight : null,
            scrollTarget: trackRef.current,
            onProgress: (p: number) => paint(p),
        })
            .then((inst: any) => {
                if (cancelled) {
                    inst && inst.destroy()
                    return
                }
                instRef.current = inst
                setStatus(inst ? "ready" : "failed")
                if (inst && inst.progress != null) paint(inst.progress)
            })
            .catch(() => setStatus("failed"))
        return () => {
            cancelled = true
            if (instRef.current) {
                instRef.current.destroy()
                instRef.current = null
            }
        }
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [props.quality, props.maxDpr, props.sectionHeight])

    /* every other scene control is applied to the live scene */
    useEffect(() => {
        const inst = instRef.current
        if (!inst) return
        inst.setOptions({
            scrollDriven: props.scrollDriven,
            autoplay: props.autoplay,
            loop: props.loop,
            speed: props.speed,
            timeOfDay: props.timeOfDay,
            cloudCover: props.cloudCover,
            grassDensity: props.grassDensity,
            waterRipples: props.waterRipples,
            palms: props.palms,
            city: props.city,
        })
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [
        props.scrollDriven, props.autoplay, props.loop, props.speed, props.timeOfDay,
        props.cloudCover, props.grassDensity, props.waterRipples, props.palms, props.city,
    ])

    /* the copy block: one per stop, stacked in the same corner as the template.
       Each stop is a real-estate act — location, exterior, interior, amenities,
       pricing — with the fact line in a glass spec pill under the headline. */
    const blocks: { key: string; eyebrow: string; head: string; sub: string; spec: string; center?: boolean }[] = [
        { key: "location", eyebrow: "01 · Location", head: props.locationHeadline, sub: props.locationSubtitle, spec: props.locationSpec },
        { key: "exterior", eyebrow: "02 · Exterior", head: props.exteriorHeadline, sub: props.exteriorSubtitle, spec: props.exteriorSpec, center: true },
        { key: "interior", eyebrow: "03 · Interior", head: props.interiorHeadline, sub: props.interiorSubtitle, spec: props.interiorSpec },
        { key: "amenities", eyebrow: "04 · Amenities", head: props.amenitiesHeadline, sub: props.amenitiesSubtitle, spec: props.amenitiesSpec },
        { key: "pricing", eyebrow: "05 · Pricing & Handover", head: props.pricingHeadline, sub: props.pricingSubtitle, spec: props.pricingSpec },
    ]

    return (
        <div
            ref={trackRef}
            style={{
                position: "relative",
                width: "100%",
                height: props.sectionHeight > 0
                    ? props.sectionHeight
                    : (props.scrollDriven ? `${props.scrollLength}vh` : "100%"),
                ...props.style,
            }}
        >
        <div
            ref={hostRef}
            className="shadestate-walkthrough"
            style={{
                position: props.scrollDriven ? "sticky" : "relative",
                top: 0,
                width: "100%",
                height: props.sectionHeight > 0
                    ? props.sectionHeight
                    : (props.scrollDriven ? "100vh" : "100%"),
                overflow: "hidden",
                background: "#0e0c09",
                fontFamily: `${JSON.stringify(props.fontFamily)}, "Timeless Sans", -apple-system, BlinkMacSystemFont, "Inter", system-ui, sans-serif`,
            }}
        >
            {props.showCopy && (
                <div style={{ position: "absolute", inset: 0, pointerEvents: "none", zIndex: 2 }}>
                    {blocks.map((b, i) => (
                        <div
                            key={b.key}
                            ref={(el) => { copyRefs.current[i] = el }}
                            style={{
                                position: "absolute",
                                left: b.center ? "50%" : "clamp(20px, 6vw, 84px)",
                                top: b.center ? "50%" : "auto",
                                bottom: b.center ? "auto" : "clamp(64px, 13vh, 130px)",
                                maxWidth: b.center ? "86%" : "min(560px, 80%)",
                                textAlign: b.center ? "center" : "left",
                                opacity: 0,
                                transform: b.center ? "translate(-50%,-50%)" : "translate3d(0,14px,0)",
                                color: "#F7F4EF",
                                pointerEvents: "none",
                                willChange: "opacity, transform",
                            }}
                        >
                            <div
                                style={{
                                    display: "flex",
                                    alignItems: "center",
                                    justifyContent: b.center ? "center" : "flex-start",
                                    gap: 12,
                                    fontSize: 10,
                                    letterSpacing: "0.28em",
                                    textTransform: "uppercase",
                                    color: "#C2A57C",
                                    marginBottom: 14,
                                    textShadow: "0 1px 14px rgba(0,0,0,.6)",
                                }}
                            >
                                {!b.center && (
                                    <span style={{ display: "block", width: 26, height: 1, background: "currentColor", opacity: 0.6 }} />
                                )}
                                {b.eyebrow}
                            </div>
                            <div
                                style={{
                                    fontFamily: `${JSON.stringify(props.fontFamily)}, "Timeless Sans", -apple-system, BlinkMacSystemFont, "Inter", system-ui, sans-serif`,
                                    fontWeight: 600,
                                    fontSize: b.center ? "clamp(52px, 10vw, 140px)" : "clamp(32px, 5vw, 72px)",
                                    fontStyle: "normal",
                                    lineHeight: 0.98,
                                    letterSpacing: b.center ? "-0.045em" : "-0.030em",
                                    textWrap: "balance" as any,
                                    textShadow: "0 2px 34px rgba(0,0,0,.42)",
                                }}
                            >
                                {b.head}
                            </div>
                            {b.sub && (
                                <div
                                    style={{
                                        marginTop: 16,
                                        maxWidth: "38ch",
                                        marginLeft: b.center ? "auto" : 0,
                                        marginRight: b.center ? "auto" : 0,
                                        fontFamily: `${JSON.stringify(props.fontFamily)}, -apple-system, BlinkMacSystemFont, "Inter", system-ui, sans-serif`,
                                        fontWeight: 300,
                                        fontSize: "clamp(12px, 1.1vw, 14px)",
                                        lineHeight: 1.7,
                                        color: "rgba(247,244,239,.74)",
                                        textShadow: "0 1px 18px rgba(0,0,0,.55)",
                                    }}
                                >
                                    {b.sub}
                                </div>
                            )}
                            {b.spec && props.showSpecs && (
                                <div
                                    style={{
                                        display: "inline-flex",
                                        alignItems: "center",
                                        gap: 9,
                                        marginTop: 18,
                                        padding: "10px 17px",
                                        border: "1px solid rgba(255,255,255,.22)",
                                        borderRadius: 980,
                                        background: "rgba(16,16,18,.38)",
                                        backdropFilter: "blur(18px) saturate(160%)",
                                        WebkitBackdropFilter: "blur(18px) saturate(160%)",
                                        boxShadow: "inset 0 1px 0 rgba(255,255,255,.26), 0 12px 30px rgba(0,0,0,.22)",
                                        fontFamily: `${JSON.stringify(props.fontFamily)}, "Timeless Sans", -apple-system, BlinkMacSystemFont, "Inter", system-ui, sans-serif`,
                                        fontSize: 11,
                                        fontWeight: 500,
                                        letterSpacing: "0.1em",
                                        lineHeight: 1.25,
                                        color: "rgba(255,255,255,.95)",
                                        whiteSpace: "nowrap",
                                        textAlign: "left",
                                        textShadow: "0 1px 10px rgba(0,0,0,.45)",
                                    }}
                                >
                                    <span
                                        style={{
                                            display: "block",
                                            flex: "none",
                                            width: 5,
                                            height: 5,
                                            borderRadius: "50%",
                                            background: "#C2A57C",
                                            boxShadow: "0 0 0 3px rgba(194,165,124,.18)",
                                        }}
                                    />
                                    {b.spec}
                                </div>
                            )}
                        </div>
                    ))}
                </div>
            )}
            {status !== "ready" && (
                <div
                    style={{
                        position: "absolute",
                        inset: 0,
                        display: "flex",
                        alignItems: "center",
                        justifyContent: "center",
                        color: "rgba(247,244,239,0.62)",
                        font: "500 12px/1.4 ui-sans-serif, system-ui, sans-serif",
                        letterSpacing: "0.14em",
                        textTransform: "uppercase",
                        pointerEvents: "none",
                    }}
                >
                    {status === "failed" ? "This device cannot display the walkthrough" : "Casa da Luz"}
                </div>
            )}
        </div>
        </div>
    )
}

