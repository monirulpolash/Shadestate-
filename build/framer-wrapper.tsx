/*  Shadestate — Casa da Luz walkthrough
    A Framer code component. The whole procedural scene is inlined below this
    wrapper (it is generated by build/build.py, so it always matches
    walkthrough/scene.js). three.js comes from npm.

    Drop the component on the canvas, size it, and set the controls in the
    right-hand panel: Camera, Look, Performance.
*/
import * as React from "react"
import { useEffect, useRef, useState } from "react"
import { addPropertyControls, ControlType } from "framer"
import * as THREE_NPM from "three"

const __THREE__ = THREE_NPM as any

/* ───────────────────────────── the scene ───────────────────────────── */
/*__SCENE__*/
/* ─────────────────────────── end of the scene ──────────────────────── */

type Props = {
    scrollDriven: boolean
    autoplay: boolean
    startStop: "approach" | "entry" | "interior" | "terrace" | "orbit"
    speed: number
    loop: boolean
    timeOfDay: "morning" | "noon" | "golden" | "dusk"
    cloudCover: number
    grassDensity: number
    waterRipples: number
    palms: boolean
    quality: "auto" | "high" | "lite"
    pausedOffscreen: boolean
    maxDpr: number
    sectionHeight: number
    style?: React.CSSProperties
}

/**
 * @framerSupportedLayoutWidth any-prefer-fixed
 * @framerSupportedLayoutHeight any-prefer-fixed
 * @framerIntrinsicWidth 1440
 * @framerIntrinsicHeight 900
 */
export default function ShadestateWalkthrough(props: Props) {
    const hostRef = useRef<HTMLDivElement>(null)
    const instRef = useRef<any>(null)
    const [status, setStatus] = useState<"loading" | "ready" | "failed">("loading")

    const look = {
        scrollDriven: props.scrollDriven,
        autoplay: props.autoplay,
        loop: props.loop,
        speed: props.speed,
        startStop: props.startStop,
        timeOfDay: props.timeOfDay,
        cloudCover: props.cloudCover,
        grassDensity: props.grassDensity,
        waterRipples: props.waterRipples,
        palms: props.palms,
        pausedOffscreen: props.pausedOffscreen,
    }

    /* mount once per quality tier / height: those rebuild the renderer */
    useEffect(() => {
        let cancelled = false
        const host = hostRef.current
        if (!host) return
        setStatus("loading")
        createWalkthrough(host, {
            ...look,
            three: THREE_NPM,
            quality: props.quality,
            dprMax: props.maxDpr,
            height: props.sectionHeight > 0 ? props.sectionHeight : null,
        })
            .then((inst: any) => {
                if (cancelled) {
                    inst && inst.destroy()
                    return
                }
                instRef.current = inst
                setStatus(inst ? "ready" : "failed")
            })
            .catch(() => setStatus("failed"))
        return () => {
            cancelled = true
            if (instRef.current) {
                instRef.current.destroy()
                instRef.current = null
            }
        }
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [props.quality, props.maxDpr, props.sectionHeight])

    /* every other control is applied to the live scene */
    useEffect(() => {
        const inst = instRef.current
        if (!inst) return
        inst.setOptions({
            scrollDriven: props.scrollDriven,
            autoplay: props.autoplay,
            loop: props.loop,
            speed: props.speed,
            timeOfDay: props.timeOfDay,
            cloudCover: props.cloudCover,
            grassDensity: props.grassDensity,
            waterRipples: props.waterRipples,
            palms: props.palms,
        })
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [
        props.scrollDriven, props.autoplay, props.loop, props.speed, props.timeOfDay,
        props.cloudCover, props.grassDensity, props.waterRipples, props.palms,
    ])

    return (
        <div
            ref={hostRef}
            className="shadestate-walkthrough"
            style={{
                position: "relative",
                width: "100%",
                height: props.sectionHeight > 0 ? props.sectionHeight : "100%",
                overflow: "hidden",
                background: "#0e0c09",
                ...props.style,
            }}
        >
            {status !== "ready" && (
                <div
                    style={{
                        position: "absolute",
                        inset: 0,
                        display: "flex",
                        alignItems: "center",
                        justifyContent: "center",
                        color: "rgba(247,244,239,0.62)",
                        font: "500 12px/1.4 ui-sans-serif, system-ui, sans-serif",
                        letterSpacing: "0.14em",
                        textTransform: "uppercase",
                        pointerEvents: "none",
                    }}
                >
                    {status === "failed" ? "This device cannot display the walkthrough" : "Casa da Luz"}
                </div>
            )}
        </div>
    )
}

